const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod, withMainActivity } = require('expo/config-plugins');
const { mergeContents } = require('@expo/config-plugins/build/utils/generateCode');

/**
 * Portrait on phones, any orientation on large screens (Android).
 *
 * `orientation: 'portrait'` in app.config.js is the product intent: DealDirect
 * is laid out for a phone held upright. Expo turns that into
 * `android:screenOrientation="portrait"` on MainActivity, which no longer
 * expresses the intent on Android:
 *
 *   - From Android 16 (target SDK 36, which this app targets), the system
 *     ignores orientation and resizability restrictions on large screens
 *     (smallest width >= 600dp: tablets, unfolded foldables, desktop windows).
 *     The lock already does nothing there.
 *   - Play reports the manifest attribute under "Remove resizability and
 *     orientation restrictions in your app to support large screen devices".
 *
 * So the attribute is removed from the manifest and MainActivity asks for
 * portrait at runtime, only when the display is phone-sized. This is the
 * pattern Android's large-screen guidance gives for "restrict orientation on
 * phones but not on large screens". iOS keeps reading `orientation` as before.
 *
 * The Kotlin lives here rather than in a separate template file because Expo's
 * fingerprint hashes this file: a change to the native code below then changes
 * the runtime version, so it can never be delivered over the air to a binary
 * built without it.
 */

const KOTLIN_HARD_KEYWORDS = new Set([
  'as', 'break', 'class', 'continue', 'do', 'else', 'false', 'for', 'fun', 'if', 'in',
  'interface', 'is', 'null', 'object', 'package', 'return', 'super', 'this', 'throw',
  'true', 'try', 'typealias', 'typeof', 'val', 'var', 'when', 'while',
]);

/** `in.dealdirect.mobile` → `` `in`.dealdirect.mobile `` (Kotlin cannot name a package segment `in`). */
function kotlinPackage(androidPackage) {
  return androidPackage
    .split('.')
    .map((segment) => (KOTLIN_HARD_KEYWORDS.has(segment) ? `\`${segment}\`` : segment))
    .join('.');
}

function orientationPolicySource(androidPackage) {
  return `package ${kotlinPackage(androidPackage)}

import android.app.Activity
import android.content.pm.ActivityInfo
import android.graphics.Rect
import android.os.Build
import android.util.DisplayMetrics
import kotlin.math.min

/**
 * Portrait on phones, any orientation on large screens.
 *
 * Generated by plugins/withPortraitOnPhones.js at prebuild; edit it there.
 *
 * Large means a smallest width of at least 600dp, the threshold Android 16
 * uses when it stops honouring orientation locks. It is measured on the
 * largest window the app can have (the display, less system decorations), not
 * the current window, so a tablet in split-screen is still a tablet.
 * Recomputed on every configuration change and on recreation, which covers
 * folding, unfolding and moving to another display.
 */
internal object OrientationPolicy {
  private const val LARGE_SCREEN_MIN_WIDTH_DP = 600f

  fun apply(activity: Activity) {
    val wanted =
        if (isLargeScreen(activity)) ActivityInfo.SCREEN_ORIENTATION_UNSPECIFIED
        else ActivityInfo.SCREEN_ORIENTATION_PORTRAIT
    if (activity.requestedOrientation != wanted) {
      activity.requestedOrientation = wanted
    }
  }

  private fun isLargeScreen(activity: Activity): Boolean {
    val bounds = maximumWindowBounds(activity)
    val density = activity.resources.displayMetrics.density
    return min(bounds.width(), bounds.height()) / density >= LARGE_SCREEN_MIN_WIDTH_DP
  }

  private fun maximumWindowBounds(activity: Activity): Rect {
    if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
      return activity.windowManager.maximumWindowMetrics.bounds
    }
    val metrics = DisplayMetrics()
    @Suppress("DEPRECATION")
    activity.windowManager.defaultDisplay.getRealMetrics(metrics)
    return Rect(0, 0, metrics.widthPixels, metrics.heightPixels)
  }
}
`;
}

/** Removes `android:screenOrientation` from MainActivity; leaves other activities alone. */
function removeMainActivityOrientation(manifest) {
  const activities = manifest.manifest.application?.[0]?.activity ?? [];
  const main = activities.find((a) => a.$['android:name'] === '.MainActivity');
  if (!main) {
    throw new Error('withPortraitOnPhones: MainActivity not found in AndroidManifest.xml.');
  }
  delete main.$['android:screenOrientation'];
  return manifest;
}

/** Calls OrientationPolicy before the activity is created and after every configuration change. */
function addOrientationPolicyCalls(mainActivity) {
  const merge = (src, tag, newSrc, anchor, offset) => {
    if (!anchor.test(src)) {
      throw new Error(`withPortraitOnPhones: MainActivity.kt has no line matching ${anchor}; update the plugin for this template.`);
    }
    return mergeContents({ tag, src, newSrc, anchor, offset, comment: '//' }).contents;
  };

  let src = mainActivity;
  src = merge(
    src,
    'dealdirect-orientation-import',
    'import android.content.res.Configuration',
    /^import android\.os\.Bundle$/m,
    1
  );
  src = merge(
    src,
    'dealdirect-orientation-config-change',
    [
      '  override fun onConfigurationChanged(newConfig: Configuration) {',
      '    super.onConfigurationChanged(newConfig)',
      '    OrientationPolicy.apply(this)',
      '  }',
    ].join('\n'),
    /^class MainActivity : ReactActivity\(\) \{$/m,
    1
  );
  src = merge(
    src,
    'dealdirect-orientation-create',
    '    OrientationPolicy.apply(this)',
    /^\s*super\.onCreate\(/m,
    0
  );
  return src;
}

function withPortraitOnPhones(config) {
  const androidPackage = config.android?.package;
  if (!androidPackage) {
    throw new Error('withPortraitOnPhones: android.package is not set.');
  }

  config = withAndroidManifest(config, (mod) => {
    mod.modResults = removeMainActivityOrientation(mod.modResults);
    return mod;
  });

  config = withDangerousMod(config, [
    'android',
    async (mod) => {
      const dir = path.join(
        mod.modRequest.platformProjectRoot,
        'app/src/main/java',
        ...androidPackage.split('.')
      );
      await fs.promises.mkdir(dir, { recursive: true });
      await fs.promises.writeFile(path.join(dir, 'OrientationPolicy.kt'), orientationPolicySource(androidPackage));
      return mod;
    },
  ]);

  config = withMainActivity(config, (mod) => {
    if (mod.modResults.language !== 'kt') {
      throw new Error('withPortraitOnPhones: expected a Kotlin MainActivity.');
    }
    mod.modResults.contents = addOrientationPolicyCalls(mod.modResults.contents);
    return mod;
  });

  return config;
}

module.exports = withPortraitOnPhones;
module.exports.kotlinPackage = kotlinPackage;
module.exports.orientationPolicySource = orientationPolicySource;
module.exports.removeMainActivityOrientation = removeMainActivityOrientation;
module.exports.addOrientationPolicyCalls = addOrientationPolicyCalls;
